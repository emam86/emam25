export function htaccess(redirects = REDIRECTS, { noindex = false } = {}) {
  const rules = Object.entries(redirects)
    .map(([from, to]) => `Redirect 301 ${from} ${to}`)
    .join('\n');
  const robots = noindex ? '\n# Staging copy: keep it out of search engines\nHeader set X-Robots-Tag "noindex, nofollow"\n' : '';
  return `# Generated by the site build. Do not edit on the server.
Options -Indexes${robots}
# One canonical address: https, no www (as the WordPress site did).
# X-Forwarded-Proto covers TLS that ends at a CDN in front of the server.
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !=https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
</IfModule>
DirectoryIndex index.html
ErrorDocument 404 /404.html

# Old WordPress URLs that are not rebuilt
${rules}
Redirect 301 /feed/ /blog/
# Photos moved from the WordPress uploads folder to /images
RedirectMatch 301 ^/wp-content/uploads/(.*)$ /images/$1
# WordPress sitemaps
RedirectMatch 301 ^/(sitemap_index|wp-sitemap|[a-z_]+-sitemap)\\.xml$ /sitemap.xml
Redirect 301 /sitemap.rss /sitemap.xml
RedirectMatch 301 ^/author/.* /about-us/
RedirectMatch 301 ^/wp-admin(/.*)?$ /
RedirectMatch 301 ^/wp-login\\.php$ /

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml text/xml
</IfModule>
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/gif "access plus 1 year"
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType text/html "access plus 10 minutes"
</IfModule>
`;
}
